-- =========================================
-- WITHDRAW PROCEDURE
-- =========================================

CREATE OR REPLACE PROCEDURE UDF_DATABASE.UDF_SCHEMA.WITHDRAW_AMOUNT(
    P_CID NUMBER,
    P_WITHDRAW_AMOUNT NUMBER(19,4)
)
RETURNS STRING
LANGUAGE SQL
AS
$$
DECLARE
    BALANCE NUMBER(19,4);
    NEW_BALANCE NUMBER(19,4);

BEGIN

    SELECT AMOUNT
    INTO :BALANCE
    FROM (
        SELECT AMOUNT
        FROM UDF_DATABASE.UDF_SCHEMA.CUSTOMERS
        WHERE CID = :P_CID
        LIMIT 1
    );

    IF (BALANCE >= P_WITHDRAW_AMOUNT) THEN

        UPDATE UDF_DATABASE.UDF_SCHEMA.CUSTOMERS
        SET 
            AMOUNT = AMOUNT - :P_WITHDRAW_AMOUNT,
            UPDATE_TIME = CURRENT_TIMESTAMP()
        WHERE CID = :P_CID;

        SELECT AMOUNT
        INTO :NEW_BALANCE
        FROM (
            SELECT AMOUNT
            FROM UDF_DATABASE.UDF_SCHEMA.CUSTOMERS
            WHERE CID = :P_CID
            LIMIT 1
        );

        RETURN 'WITHDRAW SUCCESSFUL. CURRENT BALANCE = ' || NEW_BALANCE;

    ELSE

        RETURN 'INSUFFICIENT BALANCE';

    END IF;

END;
$$;

CALL UDF_DATABASE.UDF_SCHEMA.WITHDRAW_AMOUNT(101,500);

-- =========================================
-- DEPOSIT PROCEDURE
-- =========================================

CREATE OR REPLACE PROCEDURE UDF_DATABASE.UDF_SCHEMA.DEPOSIT_AMOUNT(
    P_CID NUMBER,
    P_DEPOSIT_AMOUNT NUMBER(19,4)
)
RETURNS STRING
LANGUAGE SQL
AS
$$
DECLARE
    CURRENT_BALANCE NUMBER(19,4);
    NEW_BALANCE NUMBER(19,4);

BEGIN

    SELECT AMOUNT
    INTO :CURRENT_BALANCE
    FROM (
        SELECT AMOUNT
        FROM UDF_DATABASE.UDF_SCHEMA.CUSTOMERS
        WHERE CID = :P_CID
        LIMIT 1
    );

    UPDATE UDF_DATABASE.UDF_SCHEMA.CUSTOMERS
    SET 
        AMOUNT = AMOUNT + :P_DEPOSIT_AMOUNT,
        UPDATE_TIME = CURRENT_TIMESTAMP()
    WHERE CID = :P_CID;

    SELECT AMOUNT
    INTO :NEW_BALANCE
    FROM (
        SELECT AMOUNT
        FROM UDF_DATABASE.UDF_SCHEMA.CUSTOMERS
        WHERE CID = :P_CID
        LIMIT 1
    );

    RETURN 'DEPOSIT SUCCESSFUL. CURRENT BALANCE = ' || NEW_BALANCE;

END;
$$;

