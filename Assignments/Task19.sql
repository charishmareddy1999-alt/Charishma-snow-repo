-- =========================================
-- DELETE INACTIVE CUSTOMER
-- =========================================

CREATE OR REPLACE PROCEDURE UDF_DATABASE.UDF_SCHEMA.DELETE_INACTIVE_CUSTOMER(
    P_CID NUMBER
)
RETURNS STRING
LANGUAGE SQL
AS
$$
DECLARE
    CUSTOMER_COUNT NUMBER;

BEGIN

    SELECT COUNT(*)
    INTO :CUSTOMER_COUNT
    FROM (
        SELECT *
        FROM UDF_DATABASE.UDF_SCHEMA.CUSTOMERS
        WHERE CID = :P_CID
        AND STATUS = 'INACTIVE'
    );

    IF (CUSTOMER_COUNT > 0) THEN

        DELETE FROM UDF_DATABASE.UDF_SCHEMA.CUSTOMERS
        WHERE CID = :P_CID
        AND STATUS = 'INACTIVE';

        RETURN 'INACTIVE CUSTOMER DELETED SUCCESSFULLY';

    ELSE

        RETURN 'NO INACTIVE CUSTOMER FOUND';

    END IF;

END;
$$;

